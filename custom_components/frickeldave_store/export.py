"""Katalogexport für die Website (idempotent, ohne archivierte Produkte)."""

from __future__ import annotations

import argparse
import asyncio
import filecmp
import json
import os
import re
import shutil
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from .models import Image, Product, default_locations
from .store import CatalogStore, ImageStorage, write_json_atomic

CATALOG_SCHEMA = "http://json-schema.org/draft-04/schema#"
CATALOG_DESCRIPTION = "Generated by Frickeldave Admin"
CATALOG_RELATIVE_PATH = Path("public/data/handmade.json")
IMAGES_RELATIVE_PATH = Path("src/assets/handmade")

#: Endung einer Bilddatei, wie sie in Store und Website vorkommt.
IMAGE_SUFFIX_PATTERN = r"(?:jpg|jpeg|png|webp|gif)"
#: Nummer im Bildnamen eines Produkts (``<artikelnummer>-NN``).
_IMAGE_NUMBER_RE = re.compile(r"-(\d{2})(?:\.[A-Za-z]+)$")


def export_stock_fields(
    product: Product, locations: list[dict[str, str]] | None = None
) -> dict[str, int]:
    """Website-Schema ``stock``/``salesCabinet`` aus den Lagerstätten ableiten.

    Die Website kennt nur zwei Zahlen. Die erste Lagerstätte wird zu ``stock``,
    die zweite zu ``salesCabinet``; ohne zweite Lagerstätte bleibt
    ``salesCabinet`` bei 0. Diese Abbildung ist bewusst stabil und unabhängig
    von den Namen der Lagerstätten.
    """

    ids = [str(item["id"]) for item in (locations or default_locations())]
    return {
        "salesCabinet": product.stock_for(ids[1]) if len(ids) > 1 else 0,
        "stock": product.stock_for(ids[0]) if ids else 0,
    }


def build_catalog(
    products: Iterable[Product],
    *,
    visible_only: bool = False,
    locations: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    """Katalog im Live-Schema der Website erzeugen (ohne interne Felder)."""

    entries: list[dict[str, Any]] = []
    for product in sorted(products, key=lambda item: item.article_number):
        if product.archived:
            continue
        if visible_only and not product.visible:
            continue
        entries.append(
            {
                "name": product.name,
                "description": product.description,
                "tags": list(product.tags),
                "price": product.price,
                "size": product.size,
                "visible": product.visible,
                "customizable": product.customizable,
                **export_stock_fields(product, locations),
                "articleNumber": product.article_number,
                "category": product.category,
            }
        )
    return {
        "$schema": CATALOG_SCHEMA,
        "description": CATALOG_DESCRIPTION,
        "products": entries,
    }


def catalog_bytes(
    products: Iterable[Product],
    *,
    locations: list[dict[str, str]] | None = None,
    visible_only: bool = False,
) -> bytes:
    """Serialisierter Katalog, byte-identisch zum Datei-Export."""

    catalog = build_catalog(products, visible_only=visible_only, locations=locations)
    return (json.dumps(catalog, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def ordered_images(product: Product) -> list[Image]:
    main = [image for image in product.images if image.is_main]
    rest = sorted(
        (image for image in product.images if not image.is_main), key=lambda item: item.name
    )
    ordered = main[:1] + rest
    if not ordered:
        ordered = sorted(product.images, key=lambda item: item.name)
    return ordered


def _own_image_number(product: Product, image: Image) -> int | None:
    prefix = f"{product.article_number}-"
    if not image.name.startswith(prefix):
        return None
    match = _IMAGE_NUMBER_RE.search(image.name)
    if match is None:
        return None
    number = int(match.group(1))
    return number if 1 <= number <= 99 else None


def _free_image_number(used: set[int]) -> int:
    for candidate in range(1, 100):
        if candidate not in used:
            return candidate
    raise ValueError("Kein freier Bildnummernbereich verfügbar.")


def published_image_names(product: Product) -> list[tuple[Image, str]]:
    """Dateiname je veröffentlichtem Bild – stabil über Veröffentlichungen hinweg.

    Das Hauptbild erhält immer ``-01``: die Website zeigt das lexikografisch erste
    Bild eines Produkts als Hauptbild. Alle übrigen Bilder behalten ihre eigene
    Nummer aus dem Store, solange sie frei ist. Dadurch bleiben die Dateinamen
    gleich, solange dasselbe Bild im Produkt bleibt; nur ein neues Hauptbild oder
    eine echte Nummernkollision verschiebt einzelne Namen.
    """

    ordered = ordered_images(product)
    used: set[int] = set()
    names: list[tuple[Image, str]] = []
    for position, image in enumerate(ordered):
        suffix = Path(image.name).suffix.casefold() or ".jpg"
        number = 1 if position == 0 else _own_image_number(product, image)
        if number is None or number in used:
            number = _free_image_number(used)
        used.add(number)
        names.append((image, f"{product.article_number}-{number:02d}{suffix}"))
    return names


def _sync_images(product: Product, images: ImageStorage, images_root: Path) -> Path:
    target_dir = images_root / product.category / product.article_number
    target_dir.mkdir(parents=True, exist_ok=True)
    desired: set[str] = set()
    for image, target_name in published_image_names(product):
        desired.add(target_name)
        target = target_dir / target_name
        source = images.path_for(product.article_number, image.name)
        if not source.is_file():
            continue
        if target.is_file() and filecmp.cmp(source, target, shallow=False):
            continue
        descriptor, tmp_name = _temp_file(target_dir)
        with os.fdopen(descriptor, "wb") as handle, source.open("rb") as source_handle:
            shutil.copyfileobj(source_handle, handle)
        os.replace(tmp_name, target)
    for existing in target_dir.iterdir():
        if existing.is_file() and existing.name not in desired:
            existing.unlink()
    return target_dir


def _temp_file(directory: Path) -> tuple[int, str]:
    import tempfile

    return tempfile.mkstemp(dir=str(directory), prefix=".export-", suffix=".tmp")


def export_catalog_sync(
    products: Iterable[Product],
    images: ImageStorage | None,
    target_dir: Path,
    *,
    visible_only: bool = False,
    locations: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    """Export synchron ausführen (läuft im Executor des Aufrufers)."""

    catalog = build_catalog(products, visible_only=visible_only, locations=locations)
    catalog_path = target_dir / CATALOG_RELATIVE_PATH
    images_root = target_dir / IMAGES_RELATIVE_PATH
    image_count = 0
    for product in products:
        if product.archived:
            continue
        if visible_only and not product.visible:
            continue
        if images is not None and product.images:
            _sync_images(product, images, images_root)
            image_count += len(product.images)

    serialised = (json.dumps(catalog, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    current = catalog_path.read_bytes() if catalog_path.is_file() else None
    if current != serialised:
        catalog_path.parent.mkdir(parents=True, exist_ok=True)
        write_json_atomic(catalog_path, catalog)
    return {
        "path": str(catalog_path),
        "images_path": str(images_root),
        "products": len(catalog["products"]),
        "images": image_count,
    }


async def async_export_catalog(
    products: Iterable[Product],
    images: ImageStorage | None,
    target_dir: Path,
    *,
    visible_only: bool = False,
    locations: list[dict[str, str]] | None = None,
) -> dict[str, Any]:
    """Export im Executor ausführen (kein blockierendes I/O im Event-Loop)."""

    return await asyncio.to_thread(
        export_catalog_sync,
        list(products),
        images,
        target_dir,
        visible_only=visible_only,
        locations=locations,
    )


def export_store_sync(data: dict[str, Any], target_dir: Path) -> dict[str, Any]:
    """Export direkt aus einem Store-JSON (CLI-Pfad, ohne HA-Laufzeit)."""

    locations = [
        {"id": str(item["id"]), "name": str(item["name"])}
        for item in (data.get("locations") or default_locations())
    ]
    ids = [item["id"] for item in locations]
    products = [
        Product.from_dict(item, location_ids=ids) for item in data.get("products", []) or []
    ]
    images_base = target_dir / "images"
    return export_catalog_sync(products, ImageStorage(images_base), target_dir, locations=locations)


async def async_export_store(store: CatalogStore, target_dir: Path) -> dict[str, Any]:
    return await async_export_catalog(
        store.products(), store.images, target_dir, locations=store.locations()
    )


def main(argv: list[str] | None = None) -> int:
    """``python -m custom_components.frickeldave_store.export <store.json> <ziel>``."""

    parser = argparse.ArgumentParser(
        prog="python -m custom_components.frickeldave_store.export",
        description="Exportiert den Frickeldave-Store als Website-Katalog.",
    )
    parser.add_argument(
        "store",
        type=Path,
        help=(
            "Pfad zur Store-JSON (z. B. config/frickeldave_store/frickeldave_store.data; "
            "der Schlüssel 'data' wird automatisch erkannt)."
        ),
    )
    parser.add_argument(
        "target",
        type=Path,
        help="Zielverzeichnis (Website-Repository-Wurzel oder Exportordner).",
    )
    parser.add_argument(
        "--images-dir",
        type=Path,
        default=None,
        help="Alternatives Bildverzeichnis (Standard: <ziel>/images).",
    )
    parser.add_argument(
        "--visible-only",
        action="store_true",
        help="Nur sichtbare Produkte exportieren.",
    )
    args = parser.parse_args(argv)

    if not args.store.is_file():
        print(f"Store-Datei nicht gefunden: {args.store}", file=sys.stderr)
        return 2
    payload = json.loads(args.store.read_text(encoding="utf-8"))
    if isinstance(payload, dict) and "data" in payload and "products" not in payload:
        payload = payload["data"]
    locations = [
        {"id": str(item["id"]), "name": str(item["name"])}
        for item in (payload.get("locations") or default_locations())
    ]
    ids = [item["id"] for item in locations]
    products = [
        Product.from_dict(item, location_ids=ids) for item in payload.get("products", []) or []
    ]
    images = ImageStorage(args.images_dir or (args.target / "images"))
    result = export_catalog_sync(
        products, images, args.target, visible_only=args.visible_only, locations=locations
    )

    manifest = args.target / "frickeldave_store_export.json"
    write_json_atomic(manifest, result)
    print(json.dumps(result, ensure_ascii=False))
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI
    raise SystemExit(main())
