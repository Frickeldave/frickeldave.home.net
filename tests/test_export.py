"""Tests für den Website-Export: Feldschema, Ausschluss, Idempotenz."""

from __future__ import annotations

import json
from pathlib import Path

from custom_components.frickeldave_store.export import (
    build_catalog,
    export_catalog_sync,
    main,
)
from custom_components.frickeldave_store.models import Image, Product
from custom_components.frickeldave_store.store import ImageStorage


def _product(**overrides: object) -> Product:
    data: dict[str, object] = {
        "article_number": "LAH3K3",
        "name": "Schild",
        "category": "LA",
        "price": 35.0,
        "description": "Beschreibung",
        "size": "25cm",
        "tags": ["Holz"],
        "customizable": True,
        "visible": True,
        "stock": 2,
        "sales_cabinet": 1,
    }
    data.update(overrides)
    return Product(**data)  # type: ignore[arg-type]


def test_catalog_matches_live_schema_and_excludes_archived() -> None:
    catalog = build_catalog(
        [
            _product(),
            _product(article_number="EP0001", category="EP", archived=True),
        ]
    )
    assert catalog["$schema"] == "http://json-schema.org/draft-04/schema#"
    assert catalog["description"] == "Generated by Frickeldave Admin"
    assert len(catalog["products"]) == 1
    entry = catalog["products"][0]
    assert list(entry) == [
        "name",
        "description",
        "tags",
        "price",
        "size",
        "visible",
        "customizable",
        "salesCabinet",
        "stock",
        "articleNumber",
        "category",
    ]
    assert entry["stock"] == 2
    assert entry["salesCabinet"] == 1


def test_export_is_idempotent_and_orders_main_image_first(tmp_path: Path) -> None:
    images = ImageStorage(tmp_path / "images")
    product = _product(
        images=[
            Image(name="LAH3K3-02.jpg", is_main=False),
            Image(name="LAH3K3-01.jpg", is_main=True),
        ]
    )
    for name in ("LAH3K3-01.jpg", "LAH3K3-02.jpg"):
        target = images.path_for("LAH3K3", name)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(name.encode("utf-8"))

    target_dir = tmp_path / "website"
    stale = target_dir / "src/assets/handmade/LA/LAH3K3/LAH3K3-09.jpg"
    stale.parent.mkdir(parents=True, exist_ok=True)
    stale.write_bytes(b"alt")

    first = export_catalog_sync([product], images, target_dir)
    assert first["products"] == 1
    catalog_file = target_dir / "public/data/handmade.json"
    first_bytes = catalog_file.read_bytes()
    expected = json.dumps(json.loads(first_bytes), ensure_ascii=False, indent=2) + "\n"
    assert first_bytes == expected.encode()

    image_dir = target_dir / "src/assets/handmade/LA/LAH3K3"
    exported = sorted(item.name for item in image_dir.iterdir())
    assert exported == ["LAH3K3-01.jpg", "LAH3K3-02.jpg"]
    assert (image_dir / "LAH3K3-01.jpg").read_bytes() == b"LAH3K3-01.jpg"

    second = export_catalog_sync([product], images, target_dir)
    assert second["products"] == 1
    assert catalog_file.read_bytes() == first_bytes
    assert sorted(item.name for item in image_dir.iterdir()) == exported


def test_export_can_filter_visible_only(tmp_path: Path) -> None:
    catalog = build_catalog([_product(visible=False)], visible_only=True)
    assert catalog["products"] == []
    catalog = build_catalog([_product(visible=False)])
    assert catalog["products"][0]["visible"] is False


def test_cli_exports_and_writes_manifest(tmp_path: Path) -> None:
    store_file = tmp_path / "store.json"
    store_file.write_text(
        json.dumps({"data": {"schemaVersion": 1, "products": [_product().to_dict()]}}),
        encoding="utf-8",
    )
    target_dir = tmp_path / "out"
    exit_code = main([str(store_file), str(target_dir)])
    assert exit_code == 0
    assert (target_dir / "public/data/handmade.json").is_file()
    manifest = json.loads((target_dir / "frickeldave_store_export.json").read_text())
    assert manifest["products"] == 1
